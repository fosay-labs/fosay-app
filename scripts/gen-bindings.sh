#!/usr/bin/env bash
# Regenerates TypeScript bindings for the FOSAY contracts from a sibling checkout of
# fosay-labs/fosay-contract (override with FOSAY_CONTRACT_DIR). Requires Stellar CLI >= 25.2.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONTRACT_DIR="${FOSAY_CONTRACT_DIR:-$ROOT/../fosay-contract}"
OUT="$ROOT/packages/sdk/src/generated"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

command -v stellar >/dev/null || { echo "stellar CLI not found (cargo install --locked stellar-cli@30.0.1)"; exit 1; }
[ -d "$CONTRACT_DIR/contracts" ] || { echo "fosay-contract not found at $CONTRACT_DIR"; exit 1; }

(cd "$CONTRACT_DIR" && stellar contract build >/dev/null)
mkdir -p "$OUT"
for pair in "fosay_mandate_policy:mandate-policy" "fosay_approvals:approvals"; do
  wasm="${pair%%:*}"; name="${pair##*:}"
  stellar contract bindings typescript \
    --wasm "$CONTRACT_DIR/target/wasm32v1-none/release/$wasm.wasm" \
    --output-dir "$TMP/$name" --overwrite >/dev/null
  {
    echo "// @ts-nocheck -- generated by \`stellar contract bindings typescript\`; do not edit."
    echo "// Source: fosay-contract @ $(git -C "$CONTRACT_DIR" rev-parse --short HEAD), $wasm.wasm sha256 $(sha256sum "$CONTRACT_DIR/target/wasm32v1-none/release/$wasm.wasm" | cut -c1-16)…"
    cat "$TMP/$name/src/index.ts"
  } > "$OUT/$name.ts"
  echo "wrote packages/sdk/src/generated/$name.ts"
done
